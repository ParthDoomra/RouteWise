"""Notifications Router for RouteWise (require_manager)."""

from typing import List, Optional

from fastapi import APIRouter, Depends, Query
from sqlalchemy.orm import Session

from app.database import get_db
from app.models.notification import Notification
from app.schemas.notifications import NotificationResponse
from app.services.auth_deps import require_manager

router = APIRouter(tags=["Notifications"])


@router.get("/notifications", response_model=List[NotificationResponse])
def get_notifications(
    is_ai_generated: Optional[bool] = Query(
        None,
        description="Filter by whether notification was generated by AI",
    ),
    db: Session = Depends(get_db),
    _current_user: dict = Depends(require_manager),
):
    """List system notifications, optionally filtered by AI generation status (Manager only)."""
    query = db.query(Notification)
    if is_ai_generated is not None:
        query = query.filter(Notification.is_ai_generated == is_ai_generated)
    return query.order_by(Notification.sent_at.desc()).all()
